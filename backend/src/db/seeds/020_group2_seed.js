/**
 * Group 2 demo seed (dev only). Runs after 010_group1_seed.js and refuses to run without it.
 * Covers every Group 2 flow:
 *   merchandise  category, 2 products, 5 size variants with stock (one out of stock, two low with
 *                OPEN alerts), a CONFIRMED order (pickup code DEMXPK21) and a PENDING_PAYMENT order
 *   payments     SUCCEEDED membership dues, SUCCEEDED merch order, INITIATED merch order
 *   fundraiser   ACTIVE "Winter Bake Sale" with TODO / IN_PROGRESS / DONE tasks and cash income
 *   finance      budget; expenses SUBMITTED, APPROVED, PAID (reimbursement) and PAID (direct);
 *                receipt files written under UPLOAD_DIR
 *   ledger       IN 50 000 + 90 000 + 25 000 = 165 000; OUT 12 000 + 8 000 = 20 000 paise.
 *                Reconciliation (LLD §2.10 a–d) is consistent: every SUCCEEDED payment and PAID
 *                expense has exactly one ledger row, and nothing else does.
 * Idempotent: fixed ids + INSERT … ON CONFLICT DO NOTHING (no UPDATEs, so the append-only
 * ledger and stock-movement triggers are never hit). Receipt files are written only if missing.
 *
 * Note: the PENDING_PAYMENT order holds stock for RESERVATION_HOLD_MINUTES (15). With
 * JOBS_ENABLED=true the reservation-expiry job then expires it (payment EXPIRED, stock released)
 * — that is the intended behaviour. Re-seeding does not recreate it.
 */

const ist = (date) => new Date(`${date}T00:00:00+05:30`);

function demoPdf(title) {
  return Buffer.from(`%PDF-1.4\n% Demo receipt generated by the dev seed: ${title}\n1 0 obj << /Type /Catalog >> endobj\ntrailer << /Root 1 0 R >>\n%%EOF\n`);
}

async function writeReceipt(root, storageKey, buffer) {
  const full = path.join(root, storageKey);
  try {
    await access(full);
  } catch {
    await mkdir(path.dirname(full), { recursive: true, mode: 0o750 });
    await writeFile(full, buffer, { mode: 0o640 });
  }
}

